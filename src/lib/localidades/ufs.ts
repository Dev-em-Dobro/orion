export type Uf = (typeof UFS)[number]["sigla"];

export function ufValida(raw: string | null | undefined): Uf | null {
  const v = (raw ?? "").trim().toUpperCase();
  return UFS.some((u) => u.sigla === v) ? (v as Uf) : null;
}
